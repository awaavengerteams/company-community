/**
 * ★★★ ค่าที่แทรกเข้าไปถูกกั้นทิศไว้เสมอ ไม่ปล่อยให้ปนกับประโยค
 *
 *     ชื่อห้อง ชื่อคน ชื่อเพลง เป็นภาษาอะไรก็ได้ ★ แต่ประโยคที่มันไปแทรก
 *       เป็นภาษาที่คนอ่านเลือกไว้ — สองอย่างนี้อาจคนละทิศกัน
 *
 *     ★★ "เข้าห้อง {name}" ในภาษาอาหรับ ที่ชื่อห้องเป็นภาษาไทย:
 *        ถ้าไม่กั้น เบราว์เซอร์จะลากคำไทยไปวางผิดที่ในประโยคอาหรับ
 *        หนักสุดคือเครื่องหมายวรรคตอนของประโยคกระเด็นไปอยู่อีกฝั่ง
 *
 *     U+2068 (FSI) บอกว่า "ก้อนนี้เดาทิศของตัวเอง" และ U+2069 (PDI) ปิดก้อน
 *     ★ ข้างในเป็นทิศอะไรก็ไม่กระทบประโยคข้างนอกเลยแม้แต่ตัวเดียว
 *
 *     ★★ สองตัวนี้มองไม่เห็นและไม่กินที่ — เป็นอักขระควบคุมทิศ ไม่ใช่ตัวอักษร
 *        ★ โปรแกรมอ่านหน้าจอข้ามมันไปเอง จึงใส่ใน aria-label ได้โดยไม่เสียอะไร
 *
 *     ★ ด่าน scripts/i18n-test.ts ใช้รอยนี้เป็นเครื่องหมายด้วย: อะไรที่อยู่ใน
 *       วงเล็บคู่นี้คือของที่มาจากตัวแปร ไม่ใช่ข้อความที่ลืมแปล
 */
const ISOLATE_START = '⁨'
const ISOLATE_END = '⁩'

export function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars[name]
    return value === undefined ? whole : `${ISOLATE_START}${String(value)}${ISOLATE_END}`
  })
}

export type Translate = (key: DictKey, vars?: Record<string, string | number>) => string

/**
 * สร้างตัวแปลจากดิกชันนารีที่ให้มา
 *
 * ★ รับ "ดิกชันนารี" ไม่ใช่ "ชื่อภาษา" — คนเรียกเป็นคนหาดิกชันนารีมาเอง
 *   ฝั่ง server หาจากไฟล์ ฝั่ง client รับมาทาง props
 *   ★★ ไฟล์นี้จึงไม่ต้องรู้จักภาษาไหนเลย และไม่ต้องโตตามจำนวนภาษา
 */
export function makeTranslator(dict: Partial<Dict>, fallback?: Partial<Dict>): Translate {
  return (key, vars) => {
    /*
     * ★ กุญแจที่ยังไม่ได้แปล ตกไปที่ภาษาสำรอง (ไทย) ไม่ใช่โชว์ชื่อกุญแจ
     *   คนใช้ภาษาอื่นควรเห็นข้อความที่อ่านออก ดีกว่าเห็น "room.actions.skip"
     *   ซึ่งไม่มีความหมายกับใครเลย
     */
    const template = dict[key] ?? fallback?.[key] ?? key
    return fill(template, vars)
  }
}
