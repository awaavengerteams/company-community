/**
 * ตัดชื่อเพลงเป็นคำ
 *
 * ★ ภาษาไทยไม่มีช่องว่างระหว่างคำ การ split ด้วยช่องว่างจึงได้ก้อนยาว ๆ
 *   ★★ ซึ่งกลับกลายเป็นข้อดีตรงนี้: ก้อนไทยที่ตรงกันเป๊ะมักเป็นชื่อศิลปิน
 *      หรือชื่อเพลงจริง ๆ — แม่นกว่าการตัดคำผิด ๆ แล้วเจอคำสั้นตรงกันมั่ว
 *
 * ★ ตัดคำยาวน้อยกว่า 3 ทิ้ง — "ๆ" "of" "ที่" ไม่ได้บอกอะไร
 */
export function titleTokens(title: string): Set<string> {
  const cleaned = title
    .toLowerCase()
    // วงเล็บกับอักขระคั่นกลายเป็นช่องว่าง ไม่ใช่ถูกลบ (ไม่งั้นคำติดกัน)
    .replace(/[[\]()（）「」【】|/\\,.:;!?"'’“”\-–—_+*#~]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

  const out = new Set<string>()
  for (const raw of cleaned.split(' ')) {
    const word = raw.trim()
    if (word.length < 3) continue
    if (STOPWORDS.has(word)) continue
    if (/^\d+$/.test(word)) continue
    out.add(word)
  }
  return out
}

/**
 * ★★★ คำที่หายาก มีค่ามากกว่าคำที่เจอทั่วไป
 *
 *     รอบแรกนับ "จำนวนคำที่ซ้ำกัน" เฉย ๆ ★ ซึ่งทำให้คำว่า "genie" ที่โผล่
 *       ในชื่อเพลง 200 เพลงของค่ายเดียวกัน มีค่าเท่ากับคำว่า "palmy"
 *       ที่โผล่แค่ 3 เพลง — ทั้งที่อันหลังคือชื่อศิลปินซึ่งบอกทุกอย่าง
 *
 *     ★★ สูตรนี้คือ IDF ของวงการค้นหา: คำยิ่งเจอน้อย ยิ่งบอกอะไรได้มาก
 *        ★ ข้อดีที่สำคัญกว่าความแม่นคือมัน "ปรับตัวเอง" — วันที่เว็บมีเพลง
 *          ลูกทุ่งเยอะขึ้น คำที่เคยหายากจะกลายเป็นคำธรรมดาโดยไม่ต้องแก้โค้ด
 *
 *     ★ และมันทำงานแทน STOPWORDS ได้ครึ่งหนึ่งโดยอัตโนมัติ — คำอย่าง
 *       "official" ถ้าหลุดรายการมา ก็จะได้น้ำหนักเกือบศูนย์อยู่ดี
 *       (ยังเก็บรายการไว้เพราะมันช่วยตอนกองเพลงยังเล็กและ df ยังไม่นิ่ง)
 */
function idf(df: number, total: number): number {
  if (total <= 1) return 1
  return Math.log(total / (1 + df)) / Math.log(total)
}

