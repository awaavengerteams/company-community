/**
 * คะแนนคำที่ซ้ำกัน ถ่วงด้วยความหายากของแต่ละคำ
 *
 * ★ คืน `key` มาด้วย = ชุดคำที่ตรงกัน เรียงแล้วต่อเป็นสตริง
 *   ★★ ใช้แยก "เพลงเดียวกันคนละคลิป" ออกจาก "เพลงอื่นของศิลปินคนเดียวกัน"
 *      (ดูเหตุผลเต็มที่ diversify())
 */
function weightedOverlap(
  a: Set<string>,
  b: Set<string>,
  df: Map<string, number>,
  total: number,
): { score: number; key: string } {
  if (a.size === 0 || b.size === 0) return { score: 0, key: '' }
  // ★ วนชุดที่เล็กกว่าเสมอ — ชื่อเพลงยาว 20 คำเทียบกับ 3 คำ ไม่ต้องวน 20 รอบ
  const [small, large] = a.size <= b.size ? [a, b] : [b, a]
  let sum = 0
  const shared: string[] = []
  for (const word of small) {
    if (!large.has(word)) continue
    sum += idf(df.get(word) ?? 0, total)
    shared.push(word)
  }
  /*
   * ★ คิดสัดส่วนจากคำของ "เพลงต้นทาง" (a) เสมอ ไม่ใช่จากชุดที่เล็กกว่า
   *   ★★ คลิปคาราโอเกะมีคำเกินมาเยอะ (คาราโอเกะ · original · karaoke)
   *      ถ้าหารด้วยคำของมัน สัดส่วนจะต่ำจนไม่ถูกจับว่าเป็นเพลงเดียวกัน
   */
  const sameSong = shared.length / a.size >= SAME_SONG_RATIO
  return { score: sum, key: sameSong ? shared.sort().join('|') : '' }
}

